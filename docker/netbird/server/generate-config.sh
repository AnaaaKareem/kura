#!/bin/sh
# ==============================================================================
# Creates the NetBird server's configuration (with its secret keys) ONCE, in
# secrets/netbird_config.yaml, which docker-compose.yml mounts as a Docker
# secret. Never overwrites an existing file: new keys would lock out every
# connected device and make the stored data unreadable.
#
#     sh docker/netbird/server/generate-config.sh
#
# Based on NetBird v0.82.0's official getting-started.sh (render_combined_yaml),
# adapted for Kura: our own nginx in front, a LAN name instead of a public one.
# ==============================================================================
set -e
cd "$(dirname "$0")/../../.."

# The name admins use to reach the VPN server (LAN DNS or hosts-file entry).
NETBIRD_DOMAIN=${NETBIRD_DOMAIN:-netbird.kura.lan}
CONFIG_FILE=secrets/netbird_config.yaml

if [ -f "$CONFIG_FILE" ]; then
    echo "kept      $CONFIG_FILE (already exists; never overwritten)"
    exit 0
fi

# Random secrets, generated like NetBird's own script does:
#  - relay secret: lets the relay check that peers were sent by this server
#  - datastore key: encrypts sensitive fields in NetBird's database
#    (it must keep its base64 "=" padding)
#  - cookie key: encrypts the login session cookies of the embedded IdP
RELAY_SECRET=$(openssl rand -base64 32 | tr -d '=\n')
DATASTORE_KEY=$(openssl rand -base64 32 | tr -d '\n')
COOKIE_KEY=$(openssl rand -base64 32 | tr -d '\n')

# 644: the server container must be able to read its mounted copy (the secrets
# folder itself is 700, so other users on the host cannot open it).
umask 022
cat > "$CONFIG_FILE" <<CONF
# NetBird combined server configuration for Kura (generated by
# docker/netbird/server/generate-config.sh). Contains secret keys: never commit.
server:
  # Listen on 8080 inside the container (no root port needed); Kura's
  # netbird-proxy (nginx, TLS) forwards https://$NETBIRD_DOMAIN to it.
  listenAddress: ":8080"
  exposedAddress: "https://$NETBIRD_DOMAIN:443"
  stunPorts:
    - 3478
  metricsPort: 9090
  healthcheckAddress: ":9000"
  logLevel: "info"
  logFile: "console"

  authSecret: "$RELAY_SECRET"
  dataDir: "/var/lib/netbird"
  # The GeoLite location database is downloaded ONCE (NetBird requires it to
  # start) and kept in the data volume; no later automatic updates.
  disableGeoliteUpdate: true
  # Do not send anonymous usage statistics to NetBird.
  disableAnonymousMetrics: true

  # Embedded identity provider (local users, TOTP MFA).
  auth:
    issuer: "https://$NETBIRD_DOMAIN/oauth2"
    signKeyRefreshEnabled: true
    sessionCookieEncryptionKey: "$COOKIE_KEY"
    dashboardRedirectURIs:
      - "https://$NETBIRD_DOMAIN/nb-auth"
      - "https://$NETBIRD_DOMAIN/nb-silent-auth"
    cliRedirectURIs:
      - "http://localhost:53000/"

  # Only Kura's netbird-proxy (fixed address) may pass on client addresses.
  reverseProxy:
    trustedHTTPProxies:
      - "172.28.40.10/32"

  store:
    engine: "sqlite"
    encryptionKey: "$DATASTORE_KEY"
CONF
echo "generated $CONFIG_FILE"
